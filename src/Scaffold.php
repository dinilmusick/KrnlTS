<?php
declare(strict_types=1);

namespace SkipoWP;

use Symfony\Component\Filesystem\Filesystem;

final class Scaffold {
    public function __construct(private Filesystem $filesystem = new Filesystem()) {}

    public function create(string $root, Manifest $manifest): void {
        $slug = $this->slug($manifest->name);
        $this->filesystem->mkdir([$root . '/src', $root . '/assets', $root . '/tests']);
        $this->filesystem->dumpFile($root . '/skipo.json', json_encode($manifest->toArray(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
        $this->filesystem->dumpFile($root . '/src/App.php', "<?php\ndeclare(strict_types=1);\n\nnamespace App;\n\nuse SkipoWP\\Backend\\BackendFacade;\n\nfinal class App {\n    public function __construct(public readonly BackendFacade \$backend = new BackendFacade()) {}\n}\n");
        $this->filesystem->dumpFile($root . '/' . $slug . '.php', $this->pluginBootstrap($manifest));
        $this->filesystem->dumpFile($root . '/README.md', "# {$manifest->name}\n\nGenerated by SkipoWP application composition engine.\n");
    }

    private function slug(string $name): string {
        return strtolower(trim((string) preg_replace('/[^a-z0-9]+/i', '-', $name), ' -'));
    }

    private function pluginBootstrap(Manifest $manifest): string {
        $name = addslashes($manifest->name);
        return "<?php\n/**\n * Plugin Name: {$name}\n * Version: 0.1.0\n */\ndefined('ABSPATH') || exit;\nrequire_once __DIR__ . '/vendor/autoload.php';\n";
    }
}